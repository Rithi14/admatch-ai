import { AlertCircle, CheckCircle2, FlaskConical, Server, Tag } from 'lucide-react';
import { SEVERITY_LABELS, VERIFY_LABELS } from '../../utils/constants';

/** Severity / priority pill. `none` renders as "Supported". */
export function SeverityBadge({ severity, label }) {
  return <span className={`badge badge-${severity}`}>{label || SEVERITY_LABELS[severity] || severity}</span>;
}

export function StatusBadge({ status }) {
  if (status === 'failed') {
    return (
      <span className="badge badge-failed">
        <AlertCircle size={12} aria-hidden="true" /> Failed
      </span>
    );
  }
  return (
    <span className="badge badge-done">
      <CheckCircle2 size={12} aria-hidden="true" /> Completed
    </span>
  );
}

export function ModeBadge({ mode }) {
  return mode === 'live' ? (
    <span className="badge badge-live">
      <Server size={12} aria-hidden="true" /> Live
    </span>
  ) : (
    <span className="badge badge-demo">
      <FlaskConical size={12} aria-hidden="true" /> Demo
    </span>
  );
}

export function SampleBadge() {
  return (
    <span className="badge badge-sample" title="Built-in example audit generated by the demo engine">
      <Tag size={12} aria-hidden="true" /> Sample
    </span>
  );
}

export function VerifyBadge({ state }) {
  return <span className={`verify verify-${state}`}>{VERIFY_LABELS[state] || state}</span>;
}
